def get_stub_deck_list(deck_name: str) -> dict | None:
    """Return {card_name: qty} mainboard dict for a named deck."""
    key = deck_name.lower().replace(" ","_").replace("'","").replace("/","_")
    # Exact match
    if key in _DB_DECKS:
        return _DB_DECKS[key]["mainboard"]
    # Partial match on archetype name
    for k, v in _DB_DECKS.items():
        if key in k or k in key:
            return v["mainboard"]
    return None


def get_format_decks(format_name: str) -> dict:
    """Return all decks for a given format."""
    return {k: v for k, v in _DB_DECKS.items()
            if v["format"] == format_name}