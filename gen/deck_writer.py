"""
gen/deck_writer.py -- Emit a DeckCandidate as a runnable deck file + metadata.

Writes:
  decks/auto/<slug>_<fmt>.txt   -- standard mtg-sim deck file (ASCII), with an
                                   `audit:custom_variant` header so scripts/full_audit.py
                                   treats the nonstandard origin as intentional.
  data/auto_pipeline/candidates/<deck_id>.json -- the DeckCandidate (lineage/provenance).

The .txt is the canonical artifact every existing tool (sim.py, parallel_sim.py,
full_audit.py) can consume with no special-casing.
"""

import os
import re
import json

from gen import REPO_ROOT, PIPELINE_DATA, AUTO_DECKS_DIR


def slugify(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return s or "deck"


def deck_id(cand) -> str:
    return slugify(cand.name)


def render_deck_text(cand, fmt: str = "modern", pool=None) -> str:
    """Render the canonical <QTY> <NAME> deck file text."""
    lines = []
    lines.append(f"// {cand.name} - auto-generated by gen/ pipeline")
    lines.append(f"// Packages: {', '.join(cand.packages)}")
    lines.append(f"// Color identity: {''.join(cand.color_identity) or 'C'}")
    fid = cand.metadata.get("fidelity", "unknown")
    cast = cand.metadata.get("castability")
    extra = f" | castability {cast}" if cast is not None else ""
    lines.append(f"// Main: {cand.main_count()} | Sideboard: {sum(cand.sideboard.values())} "
                 f"(audit:custom_variant -- generated; fidelity {fid}{extra})")
    lines.append("")

    # split lands last for readability (uses pool if available)
    def is_land(n):
        return pool is not None and pool.get(n) is not None and pool.get(n).is_land

    spells = {n: q for n, q in cand.mainboard.items() if not is_land(n)}
    lands = {n: q for n, q in cand.mainboard.items() if is_land(n)}
    for name, qty in sorted(spells.items(), key=lambda x: (-x[1], x[0])):
        lines.append(f"{qty} {name}")
    if lands:
        lines.append("")
        for name, qty in sorted(lands.items(), key=lambda x: (-x[1], x[0])):
            lines.append(f"{qty} {name}")

    if cand.sideboard:
        lines.append("")
        lines.append("Sideboard")
        for name, qty in sorted(cand.sideboard.items(), key=lambda x: (-x[1], x[0])):
            lines.append(f"{qty} {name}")
    return "\n".join(lines) + "\n"


def write_candidate(cand, fmt: str = "modern", pool=None,
                    decks_dir: str = None, meta_dir: str = None) -> dict:
    """Write the deck .txt and candidate .json. Returns {deck_file, meta_file, deck_id}."""
    decks_dir = decks_dir or AUTO_DECKS_DIR
    meta_dir = meta_dir or os.path.join(PIPELINE_DATA, "candidates")
    os.makedirs(decks_dir, exist_ok=True)
    os.makedirs(meta_dir, exist_ok=True)

    did = deck_id(cand)
    deck_path = os.path.join(decks_dir, f"{did}_{fmt}.txt")
    meta_path = os.path.join(meta_dir, f"{did}.json")

    text = render_deck_text(cand, fmt=fmt, pool=pool)
    tmp = deck_path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, deck_path)

    payload = cand.to_dict()
    payload["deck_file"] = os.path.relpath(deck_path, REPO_ROOT)
    payload["format"] = fmt
    tmp = meta_path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)
    os.replace(tmp, meta_path)

    return {"deck_file": deck_path, "meta_file": meta_path, "deck_id": did}
